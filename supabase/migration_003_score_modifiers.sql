-- Migration 003: score = fuel × difficulty × pad × speed, computed by the database.
-- DESTRUCTIVE: deletes every existing worldwide score (agreed: start fresh under the
-- new rules). Run once in the Supabase SQL Editor, BEFORE pushing the game version
-- that sends fuel / flight_time / pad.

drop table if exists public.scores cascade;

create table if not exists public.scores (
    id           bigint generated always as identity primary key,
    name         text             not null check (char_length(btrim(name)) between 1 and 16),
    -- Raw run data sent by the game
    fuel         double precision not null check (fuel between 0 and 500),  -- kg left (FUEL_MASS)
    flight_time  double precision not null check (flight_time between 20 and 3600),  -- s
    pad          smallint         not null check (pad between 1 and 4),  -- 1-based, left→right
    difficulty   text             not null check (difficulty in ('EASY', 'MEDIUM', 'HARD')),
    -- Random per-computer ID generated by the game
    device_id    text             check (device_id ~ '^[0-9a-f]{32}$'),
    -- Score is computed here, never sent by the client. Must match scoring.py:
    -- fuel × difficulty × pad × speed (speed ×1.5 at ≤120 s, sliding to ×0.75 at ≥360 s)
    score        double precision generated always as (
        round(
            fuel
            * case difficulty when 'EASY' then 1.0 when 'MEDIUM' then 1.5 else 2.0 end
            * (1.0 + 0.25 * (pad - 1))
            * greatest(0.75, least(1.5, 1.5 - 0.75 * (flight_time - 120.0) / 240.0))
        )
    ) stored,
    created_at   timestamptz      not null default now()
);

alter table public.scores enable row level security;

drop policy if exists "anyone can submit a score" on public.scores;
create policy "anyone can submit a score"
    on public.scores for insert
    to anon
    with check (true);

grant insert on public.scores to anon;

-- Top n computers, one row per device_id using its best score; rows without a
-- device_id are grouped by player name. Earlier submissions win ties.
create or replace function public.top_scores(n int default 10)
returns table (name text, score real, difficulty text, created_at timestamptz)
language sql
stable
security definer
set search_path = public
as $$
    select name, score::real, difficulty, created_at
    from (
        select distinct on (coalesce(device_id, 'name:' || lower(btrim(name))))
               btrim(name) as name, score, difficulty, created_at
        from scores
        order by coalesce(device_id, 'name:' || lower(btrim(name))), score desc, created_at
    ) best
    order by score desc, created_at
    limit least(greatest(n, 1), 50);
$$;

grant execute on function public.top_scores(int) to anon;
